//! Regenerate `crates/wa-ui/src/icons_data.rs` from the Material Symbols paths
//! in `scripts/material-paths.json`.
//!
//! ```text
//! cargo run -p wa-ui --example gen_icons
//! cargo fmt --all
//! ```
//!
//! This replaces the old `scripts/gen-ui-data.mjs`; the icon data is the only
//! table that still has its source file in the tree, and the generated Rust is
//! checked in, so a normal build never needs this.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let input = root.join("scripts/material-paths.json");
    let output = root.join("crates/wa-ui/src/icons_data.rs");

    let text = std::fs::read_to_string(&input)?;
    let paths: BTreeMap<String, String> = serde_json::from_str(&text)?;

    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo run -p wa-ui --example gen_icons` from scripts/material-paths.json.\n",
    );
    out.push_str(
        "// Material Symbols (outlined, 24px) on the 960-unit grid. Do not edit by hand.\n\n",
    );
    out.push_str(
        "/// `name` -> the `<path>` body of the icon, keyed like `waIcon(name)` in the UI.\n",
    );
    out.push_str("pub static ICONS: &[(&str, &str)] = &[\n");
    for (name, body) in &paths {
        writeln!(out, "    (\"{}\", \"{}\"),", escape(name), escape(body))?;
    }
    out.push_str("];\n");

    std::fs::write(&output, out)?;
    println!("wrote {} icons to {}", paths.len(), output.display());
    Ok(())
}

/// A Rust string literal body with non-ASCII escaped, so the file stays ASCII.
fn escape(value: &str) -> String {
    let mut text = String::with_capacity(value.len());
    for ch in value.chars() {
        match ch {
            '"' => text.push_str("\\\""),
            '\\' => text.push_str("\\\\"),
            '\n' => text.push_str("\\n"),
            '\t' => text.push_str("\\t"),
            c if (c as u32) >= 0x20 && (c as u32) < 0x7f => text.push(c),
            c => {
                let _ = write!(text, "\\u{{{:X}}}", c as u32);
            }
        }
    }
    text
}
