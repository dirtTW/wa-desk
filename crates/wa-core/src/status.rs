//! status operations for `Session`.

use super::*;

impl Session {
    /// Post a text status update to every known contact, returning the server's
    /// message id so the client can show and later delete the exact update.
    ///
    /// `background_argb` is the composer background (`0xAARRGGBB`) and `font`
    /// one of `system`, `serif`, `script`, `bold`; WhatsApp renders the story
    /// for recipients with exactly these, so the colour chosen in the composer
    /// is part of the message instead of a local decoration.
    pub async fn post_status_text(
        &self,
        text: &str,
        background_argb: u32,
        font: &str,
    ) -> Result<String, String> {
        let text = text.trim();
        if text.is_empty() {
            return Err("status text is empty".into());
        }
        let background = if background_argb & 0x00FF_FFFF == 0 {
            0xFF00_A884
        } else {
            // WhatsApp stores an opaque colour; keep the alpha byte at FF.
            0xFF00_0000 | (background_argb & 0x00FF_FFFF)
        };
        let font_type = status_font_type(font);
        let recipients = self.status_recipients()?;

        let sent = self
            .client
            .status()
            .send_text(
                text,
                background,
                font_type,
                &recipients,
                Default::default(),
            )
            .await
            .map_err(|e| format!("could not post status: {e}"))?;
        // Remember the id so later "view" receipts can be attributed to it.
        self.own_statuses
            .lock()
            .expect("statuses lock")
            .insert(sent.message_id.clone());
        Ok(sent.message_id)
    }

    /// Who a status is shared with: every known person chat plus every saved
    /// contact. The saved address book is what makes posting work on a fresh
    /// start, before any chat traffic has repopulated the in-memory chat map.
    fn status_recipients(&self) -> Result<Vec<Jid>, String> {
        let mut recipients: Vec<Jid> = Vec::new();
        let mut seen: std::collections::HashSet<String> = std::collections::HashSet::new();
        for jid in self.chats.lock().expect("chats lock").values() {
            if !matches!(jid.server, Server::Pn | Server::Lid) || self.is_self_chat(&jid.to_string()) {
                continue;
            }
            if seen.insert(jid.to_string()) {
                recipients.push(jid.clone());
            }
        }
        for phone in self.contacts.lock().expect("contacts lock").keys() {
            if !(8..=15).contains(&phone.len()) || !phone.chars().all(|c| c.is_ascii_digit()) {
                continue;
            }
            let Ok(jid) = format!("{phone}@s.whatsapp.net").parse::<Jid>() else {
                continue;
            };
            if seen.insert(jid.to_string()) {
                recipients.push(jid);
            }
        }
        if recipients.is_empty() {
            return Err("no contacts to share the status with yet".into());
        }
        Ok(recipients)
    }

    /// Post an image or video status. `thumb_base64` is a small JPEG poster
    /// generated by the webview; `duration_secs` is used for videos.
    pub async fn post_status_media(
        &self,
        data_base64: &str,
        mime: &str,
        caption: &str,
        thumb_base64: &str,
        duration_secs: u32,
    ) -> Result<(), String> {
        use base64::Engine as _;
        let data = base64::engine::general_purpose::STANDARD
            .decode(data_base64)
            .map_err(|e| format!("invalid status media: {e}"))?;
        if data.is_empty() {
            return Err("the selected status media is empty".into());
        }
        let thumb = if thumb_base64.is_empty() {
            Vec::new()
        } else {
            base64::engine::general_purpose::STANDARD
                .decode(thumb_base64)
                .unwrap_or_default()
        };
        let recipients = self.status_recipients()?;
        let is_video = mime.starts_with("video/");
        let media_type = if is_video {
            MediaType::Video
        } else {
            MediaType::Image
        };
        let upload = self
            .client
            .upload(data, media_type, Default::default())
            .await
            .map_err(|e| format!("status upload failed: {e}"))?;
        let caption = Some(caption.trim()).filter(|text| !text.is_empty());
        let result = if is_video {
            self.client
                .status()
                .send_video(
                    upload,
                    thumb,
                    duration_secs.max(1),
                    caption,
                    &recipients,
                    Default::default(),
                )
                .await
        } else {
            self.client
                .status()
                .send_image(upload, thumb, caption, &recipients, Default::default())
                .await
        };
        result
            .map(|_| ())
            .map_err(|e| format!("could not post status: {e}"))
    }

    /// Ask the primary phone for the recent `status@broadcast` history. The
    /// converted updates arrive through the normal `Status` event path.
    pub async fn fetch_status_history(&self) -> Result<(), String> {
        let jid: Jid = "status@broadcast"
            .parse()
            .map_err(|e| format!("invalid status JID: {e}"))?;
        self.client
            .fetch_message_history(&jid, "", false, 0, 50)
            .await
            .map(|_| ())
            .map_err(|e| format!("status history request failed: {e}"))
    }

    /// Mark one status update as viewed. Status receipts need the author as
    /// the participant so the server can map the ack back to the poster.
    pub async fn mark_status_viewed(&self, sender: &str, id: &str) -> Result<(), String> {
        let chat: Jid = "status@broadcast"
            .parse()
            .map_err(|e| format!("invalid status JID: {e}"))?;
        let mut sender: Jid = sender
            .parse()
            .map_err(|e| format!("invalid status author: {e}"))?;
        sender.device = 0;
        sender.agent = 0;
        self.client
            .mark_as_read(&chat, Some(&sender), &[id])
            .await
            .map_err(|e| format!("status read receipt failed: {e}"))
    }

    /// React to a status update with an emoji.
    pub async fn react_status(&self, sender: &str, id: &str, emoji: &str) -> Result<(), String> {
        let chat: Jid = "status@broadcast"
            .parse()
            .map_err(|e| format!("invalid status JID: {e}"))?;
        let mut sender: Jid = sender
            .parse()
            .map_err(|e| format!("invalid status author: {e}"))?;
        sender.device = 0;
        sender.agent = 0;
        let key = wa::MessageKey {
            remote_jid: Some(chat.to_string()),
            from_me: Some(false),
            id: Some(id.to_owned()),
            participant: Some(sender.to_string()),
        };
        self.client
            .send_reaction(chat, key, emoji)
            .await
            .map(|_| ())
            .map_err(|e| format!("status reaction failed: {e}"))
    }

    /// Reply to a status update in the author's DM.
    ///
    /// The DM carries the status as its quote, like the official client: the
    /// context points at `status@broadcast` and embeds the status body — the
    /// cached protobuf for a media status, or the text the viewer showed. With
    /// no body to quote the reply goes out as a plain message rather than a
    /// half-formed quote.
    pub async fn reply_status(
        &self,
        sender: &str,
        id: &str,
        text: &str,
        status_text: Option<&str>,
    ) -> Result<(), String> {
        let text = text.trim();
        if text.is_empty() {
            return Err("status reply is empty".into());
        }
        let mut sender: Jid = sender
            .parse()
            .map_err(|e| format!("invalid status author: {e}"))?;
        sender.device = 0;
        sender.agent = 0;

        let quoted = self.status_body(id, status_text);
        let message = status_reply_body(id, &sender, text, quoted);
        self.client
            .send_message(sender, message)
            .await
            .map(|_| ())
            .map_err(|e| format!("status reply failed: {e}"))
    }

    /// The status body to embed in a reply's quote: the protobuf we cached when
    /// the status arrived, otherwise the text the viewer is showing.
    fn status_body(&self, id: &str, status_text: Option<&str>) -> Option<wa::Message> {
        let cached = {
            let mut cache = self.messages.lock().expect("media lock");
            match cache.get(id).cloned() {
                Some(entry) => Some(entry),
                None => load_media(&self.msg_dir, id).inspect(|entry| {
                    cache.insert(id.to_owned(), entry.clone());
                }),
            }
        };
        if let Some(entry) = cached {
            return Some(entry.message.as_ref().clone());
        }
        status_text
            .map(str::trim)
            .filter(|value| !value.is_empty())
            .map(|value| wa::Message {
                extended_text_message: MessageField::some(
                    wa::message::ExtendedTextMessage {
                        text: Some(value.to_owned()),
                        ..Default::default()
                    },
                ),
                ..Default::default()
            })
    }

    /// Delete one of our own status updates.
    pub async fn delete_status(&self, id: &str) -> Result<(), String> {
        let recipients = self.status_recipients()?;
        self.client
            .status()
            .revoke(id, &recipients, Default::default())
            .await
            .map(|_| ())
            .map_err(|e| format!("could not delete status: {e}"))
    }
}

/// Map the composer's font choice to the protobuf enum WhatsApp stores.
/// The DM body for a status reply: WhatsApp attaches the status as the quote so
/// the reply renders with the "· Status" card on every client. Without a body to
/// quote (a text status we never cached) the reply goes out plain rather than
/// carrying a half-formed quote.
pub(crate) fn status_reply_body(
    id: &str,
    author: &Jid,
    text: &str,
    quoted: Option<wa::Message>,
) -> wa::Message {
    let mut body = wa::message::ExtendedTextMessage {
        text: Some(text.to_owned()),
        ..Default::default()
    };
    if let Some(quoted) = quoted {
        body.context_info = MessageField::some(wa::ContextInfo {
            remote_jid: Some("status@broadcast".to_owned()),
            stanza_id: Some(id.to_owned()),
            participant: Some(author.to_string()),
            quoted_message: MessageField::some(quoted),
            ..Default::default()
        });
    }
    wa::Message {
        extended_text_message: MessageField::some(body),
        ..Default::default()
    }
}

fn status_font_type(font: &str) -> wa::message::extended_text_message::FontType {    use wa::message::extended_text_message::FontType;
    match font {
        "serif" => FontType::SystemText,
        "script" => FontType::FbScript,
        "bold" => FontType::SystemBold,
        _ => FontType::System,
    }
}