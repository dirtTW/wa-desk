// Moves the UI's data tables into Rust so the frontend stops shipping them.
//
//   node scripts/gen-ui-data.mjs
//
// Inputs (the current JavaScript sources of truth):
//   apps/desktop/ui/icons.js       Material Symbols paths
//   apps/desktop/ui/emoji-data.js  generated emoji catalogue
// Outputs:
//   crates/wa-ui/src/icons_data.rs
//   crates/wa-ui/src/emoji_data.rs
//
// Run it after `scripts/build-emoji.js` regenerates the catalogue or after
// `scripts/gen-material-icons.mjs` refreshes the icon set.
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));

const root = path.join(__dirname, "..");
const ui = path.join(root, "apps", "desktop", "ui");
const out = path.join(root, "crates", "wa-ui", "src");

// Rust string literal with every non-ASCII code point escaped, so the file is
// plain ASCII and does not depend on the editor's encoding.
function rustStr(value) {
  let text = "";
  for (const ch of String(value)) {
    const code = ch.codePointAt(0);
    if (ch === '"') text += '\\"';
    else if (ch === "\\") text += "\\\\";
    else if (ch === "\n") text += "\\n";
    else if (ch === "\t") text += "\\t";
    else if (code >= 0x20 && code < 0x7f) text += ch;
    else text += `\\u{${code.toString(16).toUpperCase()}}`;
  }
  return `"${text}"`;
}

/* ------------------------------------------------------------------ icons */

const { WA_MATERIAL_PATHS } = require(path.join(ui, "icons.js"));
const iconNames = Object.keys(WA_MATERIAL_PATHS).sort();
let icons = `// @generated by scripts/gen-ui-data.mjs from apps/desktop/ui/icons.js.
// Material Symbols (outlined, 24px) on the 960-unit grid. Do not edit by hand.

/// \`name\` -> the \`<path>\` body of the icon, keyed like \`waIcon(name)\` in the UI.
pub static ICONS: &[(&str, &str)] = &[
`;
for (const name of iconNames) {
  icons += `    (${rustStr(name)}, ${rustStr(WA_MATERIAL_PATHS[name])}),\n`;
}
icons += "];\n";
fs.writeFileSync(path.join(out, "icons_data.rs"), icons, "utf8");

/* ------------------------------------------------------------------ emoji */

const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(
  fs.readFileSync(path.join(ui, "emoji-data.js"), "utf8"),
  sandbox,
  { filename: "emoji-data.js" },
);
const groups = sandbox.window.WA_EMOJI || [];
if (!groups.length) throw new Error("emoji-data.js produced no groups");

// Category strip glyphs, one per group, matching the picker order.
const CATEGORY_ICONS = [
  "\u{1F600}", "\u{1F44D}", "\u{1F436}", "\u{1F354}", "\u2708\uFE0F",
  "\u26BD", "\u{1F4A1}", "\u2764\uFE0F", "\u{1F3C1}",
];

let emoji = `// @generated by scripts/gen-ui-data.mjs from apps/desktop/ui/emoji-data.js.
// The picker catalogue: group id, label, category glyph and (char, keywords)
// pairs. Do not edit by hand.

pub struct EmojiGroup {
    pub id: &'static str,
    pub label: &'static str,
    /// Glyph on the category strip.
    pub icon: &'static str,
    pub items: &'static [(&'static str, &'static str)],
}

pub static EMOJI_GROUPS: &[EmojiGroup] = &[
`;
let total = 0;
groups.forEach((group, index) => {
  total += group.items.length;
  emoji += `    EmojiGroup {\n        id: ${rustStr(group.id)},\n        label: ${rustStr(group.label)},\n        icon: ${rustStr(CATEGORY_ICONS[index] || "*")},\n        items: &[\n`;
  for (const [char, keywords] of group.items) {
    emoji += `            (${rustStr(char)}, ${rustStr(keywords)}),\n`;
  }
  emoji += "        ],\n    },\n";
});
emoji += "];\n";
fs.writeFileSync(path.join(out, "emoji_data.rs"), emoji, "utf8");

console.log(
  `wrote ${iconNames.length} icons and ${total} emoji in ${groups.length} groups to crates/wa-ui/src`,
);
