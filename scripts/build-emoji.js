// Generates apps/desktop/ui/emoji-data.js from the emoji.json dataset.
// Run: node scripts/build-emoji.js <emoji.json>
const fs = require("fs");
const path = require("path");

const src = process.argv[2];
if (!src) {
  console.error("usage: node build-emoji.js <emoji.json>");
  process.exit(1);
}

const raw = JSON.parse(fs.readFileSync(src, "utf8"));

const order = [
  ["Smileys & Emotion", "smileys", "Smileys"],
  ["People & Body", "people", "People"],
  ["Animals & Nature", "animals", "Animals"],
  ["Food & Drink", "food", "Food"],
  ["Travel & Places", "travel", "Travel"],
  ["Activities", "activities", "Activities"],
  ["Objects", "objects", "Objects"],
  ["Symbols", "symbols", "Symbols"],
  ["Flags", "flags", "Flags"],
];

const groups = new Map(order.map(([, id, label]) => [id, { id, label, items: [] }]));

for (const entry of raw) {
  if (!entry.char || !entry.group) continue;
  const match = order.find(([group]) => group === entry.group);
  if (!match) continue;
  // Skip modifier variants to keep the file small; base emojis cover the picker.
  if (/skin tone|component/i.test(entry.name)) continue;
  if (entry.char.length > 12) continue;

  const keywords = `${entry.name} ${entry.subgroup || ""}`.toLowerCase();
  groups.get(match[1]).items.push([entry.char, keywords.trim()]);
}

let out =
  "// Generated by scripts/build-emoji.js — emoji characters with search keywords.\n" +
  "window.WA_EMOJI = [\n";
let total = 0;
for (const [, id, label] of order) {
  const group = groups.get(id);
  if (!group.items.length) continue;
  total += group.items.length;
  out += `  { id: ${JSON.stringify(id)}, label: ${JSON.stringify(label)}, items: [\n`;
  for (const [char, keywords] of group.items) {
    out += `    [${JSON.stringify(char)}, ${JSON.stringify(keywords)}],\n`;
  }
  out += "  ]},\n";
}
out += "];\n";

const target = path.join(__dirname, "..", "apps", "desktop", "ui", "emoji-data.js");
fs.writeFileSync(target, out, "utf8");
console.log(`wrote ${total} emoji to ${target} (${fs.statSync(target).size} bytes)`);
