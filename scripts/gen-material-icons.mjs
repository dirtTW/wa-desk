// A material name may miss in the Symbols set; fall back to legacy
// Material Icons, then to these substitutes.
const FALLBACKS = {
  sticker: ["sticker", "mood"],
  edit_square: ["edit_square", "edit_note", "edit"],
  headphones: ["headphones", "headset"],
  donut_large: ["donut_large", "data_usage"],
  mail: ["mail", "mail_outline"],
  inventory_2: ["inventory_2", "archive"],
  shortcut: ["shortcut", "reply", "forward"],
};

const seen = new Set();
const uniqueNames = [];
for (const name of Object.values(MANIFEST)) {
  if (!seen.has(name)) {
    seen.add(name);
    uniqueNames.push(name);
  }
}

const out = {};
const failed = [];

async function fetchIcon(name) {
  const urls = [
    `https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined/${name}/default/24px.svg`,
    `https://fonts.gstatic.com/s/i/materialicons/${name}/v1/24px.svg`,
    `https://fonts.gstatic.com/s/i/materialiconsoutlined/${name}/v1/24px.svg`,
  ];
  for (const url of urls) {
    try {
      const res = await fetch(url);
      if (!res.ok) continue;
      const svg = await res.text();
      const inner = svg
        .replace(/^[\s\S]*?<svg[^>]*>/, "")
        .replace(/<\/svg>[\s\S]*$/, "")
        .trim();
      if (inner.includes("<path")) return inner;
    } catch {
      /* try the next URL */
    }
  }
  return null;
}

for (const name of uniqueNames) {
  let inner = await fetchIcon(name);
  if (!inner && FALLBACKS[name]) {
    for (const alt of FALLBACKS[name]) {
      inner = await fetchIcon(alt);
      if (inner) {
        console.log(`fallback: ${name} -> ${alt}`);
        break;
      }
    }
  }
  if (inner) out[name] = inner;
  else failed.push(name);
}

if (failed.length) {
  console.error("FAILED to fetch:", failed.join(", "));
}
fs.writeFileSync(
  "scripts/material-paths.json",
  JSON.stringify(out, null, 2),
);
